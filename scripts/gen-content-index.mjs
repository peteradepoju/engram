// Writes content/index.ts: one loader per lesson file, so the lesson page can import them by id.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../content/", import.meta.url).pathname;
const lines = ["// Generated by scripts/gen-content-index.mjs. Do not edit by hand.", "export const LESSONS: Record<string, () => Promise<any>> = {"];
for (const week of readdirSync(root).filter((d) => /^w\d{3}$/.test(d)).sort()) {
  for (const f of readdirSync(join(root, week)).filter((f) => /^d[1-6]\.mdx$/.test(f)).sort()) {
    lines.push(`  "${week}${f.slice(0, 2)}": () => import("./${week}/${f}"),`);
  }
}
lines.push("};", "");
writeFileSync(join(root, "index.ts"), lines.join("\n"));
console.log(`content/index.ts: ${lines.length - 3 - 1} lessons`);
